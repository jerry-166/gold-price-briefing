def walk(o, path=""):
    bad = []
    if isinstance(o, str):
        for ch, name in (('"', "ASCII quote"), ("`", "backtick"), ("**", "literal **")):
            if ch in o:
                bad.append("%s in %s" % (name, path))
    elif isinstance(o, dict):
        for k, v in o.items():
            bad += walk(v, path + "." + k)
    elif isinstance(o, list):
        for i, v in enumerate(o):
            bad += walk(v, "%s[%d]" % (path, i))
    return bad

