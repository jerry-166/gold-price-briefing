def walk(o, path=''):
    bad = []
    if isinstance(o, str):
        if '"' in o:
            bad.append(path)
    elif isinstance(o, dict):
        for k, v in o.items():
            bad += walk(v, path + '.' + k)
    elif isinstance(o, list):
        for i, v in enumerate(o):
            bad += walk(v, '%s[%d]' % (path, i))
    return bad

