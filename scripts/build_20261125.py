def walk(o, path=""):
    bad = []
    if isinstance(o, str):
        for ch, name in (("\"", "ASCII double quote"), ("`", "backtick"), ("**", "literal **")):
            if ch in o:
                bad.append(f"{name} in {path}")
    elif isinstance(o, dict):
        for k, v in o.items():
            bad.extend(walk(v, f"{path}.{k}"))
    elif isinstance(o, list):
        for i, v in enumerate(o):
            bad.extend(walk(v, f"{path}[{i}]"))
    return bad


